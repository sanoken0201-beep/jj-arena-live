def validate() -> None:
    assert len(ROWS) == 10
    seen: set[str] = set()
    numeric_wrong_67 = 0
    longest_is_wrong = 0
    for category, raw in ROWS.items():
        rows = [r.strip() for r in raw.strip().splitlines() if r.strip()]
        assert len(rows) == 2, (category, len(rows))
        for line in rows:
            parts = line.split("|")
            assert len(parts) == 9, (category, line)
            slug, prompt, correct, wrong1, wrong2, wrong3, explanation, source, difficulty = parts
            assert slug not in seen, slug
            seen.add(slug)
            assert prompt and len(prompt) < 250 and len(explanation) >= 15, slug
            assert len({correct, wrong1, wrong2, wrong3}) == 4, slug
            assert source in SOURCES and difficulty in {"standard", "intermediate"}, slug
            if "67%" in (wrong1, wrong2, wrong3):
                numeric_wrong_67 += 1
            if max(map(len, (wrong1, wrong2, wrong3))) > len(correct):
                longest_is_wrong += 1
            choices = (correct, wrong1, wrong2, wrong3)
            if all(choice.endswith("%") and choice[:-1].replace(".", "", 1).isdigit() for choice in choices):
                numbers = [float(choice[:-1]) for choice in choices]
                assert all(abs(v - numbers[0]) >= 10 for v in numbers[1:]), slug
    assert len(seen) == 20
    assert numeric_wrong_67 >= 10, numeric_wrong_67
    assert longest_is_wrong >= 6, longest_is_wrong


validate()
