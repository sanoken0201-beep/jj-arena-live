def _concepts(category, rows):
    result = []
    for row in rows.strip().splitlines():
        key, prompt, correct, wrong1, wrong2, wrong3, explanation = row.split("|")
        result.append(_q(category+"-"+key, category, CATEGORY_LABELS[category], prompt,
                         [("a", correct), ("b", wrong1), ("c", wrong2), ("d", wrong3)],
                         "a", explanation))
    return result


